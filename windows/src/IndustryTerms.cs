        public static bool IsKnown(string key)
        {
            if (string.IsNullOrEmpty(key)) return false;
            foreach (string[] d in Domains)
            {
                if (d[0] == key) return true;
            }
            return false;
        }

        /// <summary>是否是认得的行业：内置的或用户自己加的。</summary>
        public static bool IsKnownAny(string key)
        {
            if (IsKnown(key)) return true;
            return UserDict.FindIndustry(key) != null;
        }

        /// <summary>内置行业 + 用户自定义行业，供菜单和校验使用。</summary>
        public static List<string[]> AllDomains()
        {
            var list = new List<string[]>();
            foreach (string[] d in Domains) list.Add(d);
            foreach (UserIndustry ind in UserDict.Industries)
            {
                list.Add(new string[] { ind.key, ind.label });
            }
            return list;
        }

        /// <summary>是否出现在「行业词库」菜单里（内置或自定义）。</summary>
        public static bool InMenu(string key)
        {
            foreach (string[] d in AllDomains())
            {
                if (d[0] == key) return true;
            }
            return false;
        }

        public static string LabelAny(string key)
        {
            if (IsKnown(key)) return Label(key);
            return UserDict.LabelOf(key);
        }

        public static string Label(string key)
        {
            foreach (string[] d in Domains)
            {
                if (d[0] == key) return d[1];
            }
            return "自动（全部行业）";
        }

