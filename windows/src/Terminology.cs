        public class Term
        {
            public string n = "";   // 主名称
            public string a = "";   // 别名，用 | 分隔
            public string d = "";   // 一句话定义
            public string x = "";   // 生活化类比
            public string c = "";   // 领域（显示用）
            public string i = "";   // 行业代码，技术词库为空；用于按行业提权

            public string[] Aliases
            {
                get { return string.IsNullOrEmpty(a) ? new string[0] : a.Split('|'); }
            }
        }

        private static List<Term> _all;
        private static readonly object _lock = new object();

        /// <summary>当前选中的行业代码（auto 表示不偏向任何行业），由托盘菜单写入。</summary>
        public static string Domain = "auto";

        private static List<Term> All
        {
            get
            {
                if (_all != null) return _all;
                lock (_lock)
                {
                    if (_all != null) return _all;
                    var list = new List<Term>();
                    try
                    {
                        var ser = new JavaScriptSerializer { MaxJsonLength = 8 * 1024 * 1024 };
                        List<Term> baseList = ser.Deserialize<List<Term>>(RawJson);
                        if (baseList != null) list.AddRange(baseList);
                    }
                    catch { }
                    // 行业词库并到同一张表里，匹配逻辑只走一条路
                    try { list.AddRange(IndustryTerms.All); }
                    catch { }
                    // 用户自己加的词条排在最后，同样进入匹配
                    try { list.AddRange(UserDict.ToTerms()); }
                    catch { }
                    _all = list;
                    return _all;
                }
            }
        }

        /// <summary>自定义词库变动后调用，下次匹配重新合并。</summary>
        public static void Invalidate()
        {
            lock (_lock) { _all = null; }
        }

        /// <summary>词库条目总数（技术 + 行业）。</summary>
        public static int TotalCount { get { return All.Count; } }

        /// <summary>从一段文字里找出命中的术语，按出现顺序返回，最多 max 条。</summary>
        public static List<Term> Match(string text, int max)
        {
            var hits = new List<Term>();
            if (string.IsNullOrEmpty(text) || max <= 0) return hits;

            var scored = new List<KeyValuePair<int, Term>>();
            var lengths = new Dictionary<Term, int>();

            foreach (Term t in All)
            {
                int pos = -1;
                int len = t.n.Length;

                if (ContainsWord(text, t.n, out pos)) { }
                else
                {
                    int best = -1;
                    int bestLen = 0;
                    foreach (string alias in t.Aliases)
                    {
                        int p;
                        if (ContainsWord(text, alias, out p) && (best < 0 || p < best))
                        {
                            best = p;
                            bestLen = alias.Length;
                        }
                    }
                    pos = best;
                    if (bestLen > 0) len = bestLen;
                }

                if (pos < 0) continue;
                scored.Add(new KeyValuePair<int, Term>(pos, t));
                lengths[t] = len;
            }

            // 选中行业时该行业的术语先讲；其次是专有名词（Docker 比「打包」更值得讲），
            // 最后按出现位置。被更长术语盖住的（如「缓存」之于「缓存击穿」）不再重复
            scored.Sort(delegate(KeyValuePair<int, Term> a, KeyValuePair<int, Term> b)
            {
                bool aDom = DomainPreferred(a.Value);
                bool bDom = DomainPreferred(b.Value);
                if (aDom != bDom) return aDom ? -1 : 1;

                bool aProper = Weight(a.Value) == 3;
                bool bProper = Weight(b.Value) == 3;
                if (aProper != bProper) return aProper ? -1 : 1;
                return a.Key.CompareTo(b.Key);
            });
            var taken = new List<KeyValuePair<int, int>>();

            foreach (var kv in scored)
            {
                if (hits.Count >= max) break;
                int start = kv.Key;
                int len = lengths.ContainsKey(kv.Value) ? lengths[kv.Value] : kv.Value.n.Length;

                bool overlapped = false;
                foreach (var r in taken)
                {
                    if (start < r.Key + r.Value && r.Key < start + len) { overlapped = true; break; }
                }
                if (overlapped) continue;

                taken.Add(new KeyValuePair<int, int>(start, len));
                hits.Add(kv.Value);
            }
            return hits;
        }

        /// <summary>整段就是一个术语时返回它，用于只显示名词解释的场景。</summary>
        public static Term Exact(string text)
        {
            if (string.IsNullOrEmpty(text)) return null;
            string t = text.Trim().Trim('.', ',', ':', ';', '。', '，', '：', '；');
            foreach (Term term in All)
            {
                if (string.Equals(term.n, t, StringComparison.OrdinalIgnoreCase)) return term;
                foreach (string alias in term.Aliases)
                {
                    if (string.Equals(alias, t, StringComparison.OrdinalIgnoreCase)) return term;
                }
            }
            return null;
        }

        /// <summary>是否属于当前选中的行业：选了具体行业时，该行业术语优先。auto 不偏向。</summary>
        private static bool DomainPreferred(Term t)
        {
            if (string.IsNullOrEmpty(t.i)) return false;
            if (string.IsNullOrEmpty(Domain) || Domain == "auto") return false;
            return t.i == Domain;
        }

        /// <summary>术语的分量：英文专名/缩写 3，较长的中文术语 2，两字泛词 1。</summary>
        private static int Weight(Term t)
        {
            foreach (char c in t.n)
            {
                if (c >= 'A' && c <= 'Z') return 3;
            }
            return t.n.Length >= 4 ? 2 : 1;
        }

        private static bool ContainsWord(string text, string word, out int position)
        {
            position = -1;
            if (string.IsNullOrEmpty(word) || word.Length < 2) return false;

            bool ascii = true;
            foreach (char ch in word) { if (ch > 127) { ascii = false; break; } }

            if (!ascii)
            {
                int idx = text.IndexOf(word, StringComparison.Ordinal);
                if (idx < 0) return false;
                position = idx;
                return true;
            }

            int from = 0;
            while (from <= text.Length - word.Length)
            {
                int idx = text.IndexOf(word, from, StringComparison.OrdinalIgnoreCase);
                if (idx < 0) return false;

                bool leftOk = idx == 0 || !char.IsLetterOrDigit(text[idx - 1]);
                int end = idx + word.Length;
                bool rightOk = end >= text.Length || !char.IsLetterOrDigit(text[end]);

                if (leftOk && rightOk)
                {
                    position = idx;
                    return true;
                }
                from = idx + 1;
            }
            return false;
        }

